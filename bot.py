PLATE = re.compile(r"^([АВЕКМНОРСТУХABEKMHOPCTYX])(\d{3})([АВЕКМНОРСТУХABEKMHOPCTYX]{2})(\d{2,3})$", re.I)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    keyboard = [["🔎 Проверить номер", "ℹ️ О боте"]]
    await update.message.reply_text(
        "🔱 DOMINION\nRUSSIAN VEHICLE SEARCH\n\n"
        "Отправь российский госномер, например А123ВС05.",
        reply_markup=ReplyKeyboardMarkup(keyboard, resize_keyboard=True)
    )

async def message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    raw = update.message.text.strip()
    if raw == "ℹ️ О боте":
        await update.message.reply_text(
            "DOMINION определяет формат российского номера и региональный код. "
            "Поиск владельцев и персональных данных не предусмотрен."
        )
        return
    if raw == "🔎 Проверить номер":
        await update.message.reply_text("Введи номер, например А123ВС05.")
        return
    value = re.sub(r"[\s-]", "", raw.upper())
    match = PLATE.fullmatch(value)
    if not match:
        await update.message.reply_text("Формат не распознан. Пример: А123ВС05")
        return
    code = match.group(4)
    region = REGIONS.get(code, "код пока отсутствует в справочнике")
    await update.message.reply_text(
        f"🔎 Номер распознан: {value}\n"
        f"📍 Код региона: {code} — {region}\n\n"
        "🚘 Марка и модель: пока не определяются.\n"
        "Для этого нужен проверенный законный источник автомобильных данных."
    )

def main():
    if not TOKEN:
        raise RuntimeError("Set BOT_TOKEN environment variable.")
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, message))
    app.run_polling()

if __name__ == "__main__":
    main()
