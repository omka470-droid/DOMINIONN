def normalize_plate(raw: str) -> str:
    value = raw.upper().replace(" ", "").replace("-", "")
    # Convert common Latin lookalikes to Cyrillic equivalents.
    lookalikes = {"A":"А", "B":"В", "E":"Е", "K":"К", "M":"М",
                  "H":"Н", "O":"О", "P":"Р", "C":"С", "T":"Т",
                  "Y":"У", "X":"Х"}
    return "".join(lookalikes.get(ch, ch) for ch in value)

def inspect_plate(raw: str) -> str:
    plate = normalize_plate(raw)
    match = PLATE_RE.fullmatch(plate)
    if not match:
        return (
            "Не удалось распознать номер как стандартный российский гражданский "
            "госномер.\n\n"
            "Пример формата: <code>А123ВС05</code> или <code>А123ВС777</code>.\n"
            "Проверьте буквы и цифры и отправьте номер ещё раз."
        )

    region_code = match.group(4)
    region = REGIONS.get(region_code)
    if region:
        region_text = f"📍 Региональный код: <b>{region_code}</b> — {region}"
    else:
        region_text = (
            f"📍 Региональный код: <b>{region_code}</b> — "
            "код не найден во встроенном справочнике"
        )

    return (
        "✅ <b>Номер распознан</b>\n\n"
        f"🚘 Госномер: <code>{plate}</code>\n"
        "🌍 Страна: Россия\n"
        f"{region_text}\n\n"
        "ℹ️ По одному госномеру бот не устанавливает личность владельца, "
        "адрес, телефон или другие персональные данные. Марку и модель "
        "автомобиля без проверенного легального источника определить нельзя."
    )

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    await update.message.reply_text(
        "🛰 <b>DOMINION</b>\n"
        "Бот для распознавания российских автомобильных номеров.\n\n"
        "Отправь госномер сообщением, например <code>А123ВС05</code>.\n"
        "Я проверю формат и определю регион по коду.",
        parse_mode="HTML",
    )

async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    await update.message.reply_text(
        "Отправь российский госномер в формате <code>А123ВС05</code>.\n"
        "Поддерживаются стандартные номера с двух- и трёхзначным кодом региона.",
        parse_mode="HTML",
    )

async def handle_text(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    raw = (update.message.text or "").strip()
    await update.message.reply_text(inspect_plate(raw), parse_mode="HTML")

async def handle_other(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    await update.message.reply_text("Отправь госномер текстом, например А123ВС05.")

def main() -> None:
    if not TOKEN:
        raise RuntimeError("Не задан BOT_TOKEN. Добавь токен в переменные окружения.")
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(CommandHandler("help", help_command))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_text))
    app.add_handler(MessageHandler(~filters.TEXT, handle_other))
    log.info("DOMINION запущен в режиме polling")
    app.run_polling(allowed_updates=Update.ALL_TYPES)

if __name__ == "__main__":
    main()

